"""Seed the SQLite database with a real slice of Amazon Reviews 2023 classified by the trained model.

Only seeds if the database currently has zero reviews (unless --force is passed).
Every seeded prediction is generated by the real trained joblib model.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from app.database.db import SessionLocal, init_db
from app.database.models import Review
from app.services.dataset_service import process_csv_upload
from ml.download_dataset import MAIN_CSV


def seed_database(dataset_path: Path = MAIN_CSV, max_rows: int = 1200, force: bool = False) -> None:
    init_db()
    db = SessionLocal()
    try:
        existing_count = db.query(Review).count()
        if existing_count > 0 and not force:
            print(f"[seed] Database already contains {existing_count:,} reviews. Skipping seed.")
            return

        if not dataset_path.exists():
            raise FileNotFoundError(
                f"Dataset not found at {dataset_path}. Run 'python -m ml.train' first."
            )

        df = pd.read_csv(dataset_path)
        # Focus on the top 10 most-reviewed products so Product Comparison and Complaint Clustering are rich
        top_products = df["product_name"].value_counts().head(10).index.tolist()
        filtered = df[df["product_name"].isin(top_products)].copy()
        if len(filtered) > max_rows:
            # Deterministic stratified-like sample across products & dates
            filtered = filtered.sample(n=max_rows, random_state=42).sort_values("review_date")

        csv_bytes = filtered.to_csv(index=False).encode("utf-8")
        result = process_csv_upload(
            db=db,
            file_bytes=csv_bytes,
            filename="amazon_reviews_2023_initial_seed.csv",
            column_mapping={
                "review_text": "review_text",
                "rating": "rating",
                "product_name": "product_name",
                "review_date": "review_date",
            },
            source="seed",
        )
        print(
            f"[seed] Persisted {result['valid_rows']:,} real ML-classified reviews "
            f"(Positive={result['sentiment_breakdown']['Positive']}, "
            f"Neutral={result['sentiment_breakdown']['Neutral']}, "
            f"Negative={result['sentiment_breakdown']['Negative']}, "
            f"avg_conf={result['average_confidence']:.4f})"
        )
    finally:
        db.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Seed ReviewIQ SQLite database with real ML-classified reviews.")
    parser.add_argument("--max-rows", type=int, default=1200)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    seed_database(max_rows=args.max_rows, force=args.force)

